"""Human-facing text: commit messages, pull-request bodies and tracker comments."""

from __future__ import annotations

import re

from ticket2pr.domain import AgentResult, ChangeSet, PullRequest, TestReport, Ticket, Usage

_MAX_SUMMARY_CHARS = 6_000
_MAX_TEST_TAIL_CHARS = 3_000
_MAX_GUARDRAIL_LINES = 20  # GitHub refuses bodies over 65,536 characters
_MAX_GUARDRAIL_CHARS = 300
_HTML_START = re.compile(r"<(?=[A-Za-z/!?])")
_FENCE = re.compile(r"`{3,}|~{3,}")
# @user, @org/team, #123, owner/repo#45 and "Fixes #12": a zero-width space after @ or #
# keeps the text readable but stops mentions, cross-references and closing keywords.
_REFERENCE = re.compile(r"([@#])(?=[\w/-])")
# GitHub also links GH-7: a zero-width space after the G.
_GH_REFERENCE = re.compile(r"\b(G)(?=H-\d)", re.IGNORECASE)
# GitHub also honours "Fixes https://github.com/o/r/issues/7": break the keyword itself.
_CLOSING_KEYWORD = re.compile(
    r"\b(?=(?:close[sd]?|fix(?:e[sd])?|resolve[sd]?):?\s+https?://)(\w)", re.IGNORECASE
)


def commit_message(ticket: Ticket) -> str:
    # Commits and squash merges close "Fixes #12" issues too, not only the PR body.
    lines = [f"{ticket.key}: {_no_references(ticket.title)}"[:72], "", "Generated by ticket2pr."]
    if ticket.url:
        lines.append(f"Ticket: {ticket.url}")
    return "\n".join(lines)


def pr_title(ticket: Ticket) -> str:
    return f"[{ticket.key}] {_no_references(ticket.title)}"[:120]


def pr_body(
    *,
    ticket: Ticket,
    agent: AgentResult,
    usage: Usage,
    changes: ChangeSet,
    tests: TestReport,
    model: str,
    excluded: tuple[str, ...] = (),
) -> str:
    ticket_ref = f"[{ticket.key}]({ticket.url})" if ticket.url else ticket.key
    summary = _inert(agent.summary[:_MAX_SUMMARY_CHARS]) or "_The agent did not provide a summary._"
    sections = [
        f"Resolves {ticket_ref}: {_inert(ticket.title)}",
        "## Verification\n\n" + _tests_section(tests),
        "## Change size\n\n"
        f"{len(changes.files)} file(s), +{changes.insertions} / -{changes.deletions}",
        "## Agent run\n\n" + usage_table(usage, model=model),
    ]
    if agent.denied_actions or excluded:
        events = [("Blocked", action) for action in agent.denied_actions]
        events += [("Not committed (protected path)", path) for path in excluded]
        lines = [
            f"- {kind}: {_code_span(text[:_MAX_GUARDRAIL_CHARS])}"
            for kind, text in events[:_MAX_GUARDRAIL_LINES]
        ]
        if len(events) > _MAX_GUARDRAIL_LINES:
            lines.append(f"- … and {len(events) - _MAX_GUARDRAIL_LINES} more")
        sections.append("## Guardrail events\n\n" + "\n".join(lines))
    # Last, so nothing the agent writes (fake headings, layout tricks) can hide ours.
    sections.append("## Agent summary\n\n" + summary)
    sections.append("---\n_Opened by ticket2pr. Review it like any other contribution._")
    return "\n\n".join(sections)


def usage_table(usage: Usage, *, model: str) -> str:
    return (
        "| Model | Cost | Tokens (in / out / cache read / cache write) | Turns | Duration |\n"
        "|---|---|---|---|---|\n"
        f"| `{model}` | {usage.cost_label} | "
        f"{usage.input_tokens:,} / {usage.output_tokens:,} / {usage.cache_read_tokens:,} / "
        f"{usage.cache_creation_tokens:,} | "
        f"{usage.turns} | {usage.duration_s / 60:.1f} min |"
    )


def _tests_section(tests: TestReport) -> str:
    if not tests.ran:
        return "⚠️ No test command was found; this change was **not** verified by tests."
    verdict = "✅ passed" if tests.passed else "❌ failed"
    text = f"`{tests.command}` {verdict} in {tests.duration_s:.0f}s."
    if not tests.passed and tests.output_tail:
        tail = tests.output_tail[-_MAX_TEST_TAIL_CHARS:]
        fence = _fence_for(tail)
        text += (
            f"\n\n<details><summary>Output (tail)</summary>\n\n{fence}\n{tail}\n{fence}\n</details>"
        )
    return text


def _fence_for(text: str) -> str:
    """Return a code fence longer than any backtick run in ``text`` (so it cannot close early)."""
    longest = max((len(run) for run in re.findall(r"`+", text)), default=0)
    return "`" * max(3, longest + 1)


def tracker_comment(
    *,
    published: tuple[PullRequest, TestReport] | None,
    usage: Usage,
    error: str | None = None,
) -> str:
    """The ticket comment: the PR and how it was verified, or why there is none."""
    if published is None:
        reason = error or "unknown error"
        return (
            # One plain code span (the ADF converter knows no other): links in it stay text.
            f"ticket2pr could not open a pull request: {_code_span(reason.replace('`', "'"))}\n\n"
            f"Spent {usage.cost_label}."
        )
    pr, tests = published
    kind = "draft pull request" if pr.draft else "pull request"
    if not tests.ran:
        status = "No tests were run: review this change carefully."
    elif tests.passed:
        status = f"Tests pass (`{tests.command}`)."
    else:
        status = f"Tests fail (`{tests.command}`): see the PR for the output."
    return (
        f"ticket2pr opened a {kind}: [{pr.url}]({pr.url})\n\n"
        f"{status}\n\n"
        # Cost only: tokens and turns are exact numbers the agent can steer, and the ticket's
        # reporter may not be allowed to read the repository. The PR has the full usage.
        f"Cost: `{usage.cost_label}`"
    )


def _inert(markdown: str) -> str:
    """Untrusted Markdown (agent text, ticket title) without images, raw HTML, fenced blocks
    or ``[]`` links.

    The ticket can steer the agent, and GitHub fetches every image of a PR body for each
    viewer: an image URL could carry repository data out. Escaping every ``[`` (after the
    backslashes, so ``\\[`` cannot undo it) also kills reference definitions, which apply to
    the whole document. Bare URLs still autolink, but only a click follows them. shortcut:
    the escapes also show inside code blocks; parse the Markdown if that ever matters.
    """
    escaped = markdown.replace("\\", "\\\\").replace("[", "\\[")
    # No fenced blocks either: GitHub renders some (mermaid, geojson...) with remote content.
    # (Every character escaped: one escape would leave a shorter, still valid fence.)
    escaped = _FENCE.sub(lambda run: "".join(f"\\{char}" for char in run.group()), escaped)
    return _HTML_START.sub("&lt;", _no_references(escaped))


def _no_references(text: str) -> str:
    text = _CLOSING_KEYWORD.sub("\\1\u200b", text)
    text = _GH_REFERENCE.sub("\\1\u200b", text)
    return _REFERENCE.sub("\\1\u200b", text)


def _code_span(text: str) -> str:
    """Inline code that no backtick in ``text`` can close early."""
    text = " ".join(text.split())  # a code span cannot hold a blank line
    longest = max((len(run) for run in re.findall(r"`+", text)), default=0)
    ticks = "`" * (longest + 1)
    return f"{ticks} {text} {ticks}"
